"""画面全体の表示倍率を下げる CSS（Gradio の launch(css=...) に渡す）。

Gradio の既定は余白も文字も大きめで、フル HD だとページ全体が 1070px になり
縦スクロールが出る（実測）。ブラウザのズームを 80% にすると 985px に収まり
ちょうど 1 画面になるので、それと同じ状態を CSS で作る。

倍率を下げる方法は 2 つあるが、実測した結果 zoom を採る:

  font-size: 80%  -> 効果なし。Gradio は余白や高さを px で持っているため、
                     文字だけ小さくなって全体の高さは 1070px のまま変わらない
  zoom: 80%       -> 余白・文字・画像がまとめて縮み、985px に収まる

zoom は仕様上は非標準だが、Chrome / Edge / Firefox いずれも対応しており、
このツールはローカルのブラウザで開く前提なので実用上の問題はない。
"""
from __future__ import annotations

# 表示倍率。ブラウザのズーム率と同じ意味で、下げるほど一度に見える量が増える
UI_ZOOM = 80

CSS = """
/* 画面全体をブラウザのズーム __ZOOM__% と同じ見え方にする。
   フル HD で縦スクロールを出さずに収めるための調整。 */
gradio-app {
    zoom: __ZOOM__%;
}
"""


def build_css() -> str:
    return CSS.replace("__ZOOM__", str(UI_ZOOM))
